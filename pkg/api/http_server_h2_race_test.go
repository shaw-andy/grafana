// TestHTTPServerHTTP2HPACKSettingsRace fails while Grafana is built with a
// Go release that still races the HTTP/2 HPACK encoder (Go 1.26.6). A client
// that is allowed to connect can mix ordinary requests with
// SETTINGS_HEADER_TABLE_SIZE frames. The serve goroutine applies that setting
// to the shared encoder while writeFrameAsync is encoding response headers.
// The concurrent map use aborts the process, so the check runs in a child.
// The child exits 0 only when the server still answers after the exchange.
func TestHTTPServerHTTP2HPACKSettingsRace(t *testing.T) {
	if os.Getenv("GRAFANA_H2_RACE_CHILD") == "1" {
		runHTTP2HeaderTableChild(t)
		return
	}

	for _, proto := range []string{"h2", "socket_h2"} {
		t.Run(proto, func(t *testing.T) {
			cmd := exec.Command(os.Args[0],
				"-test.run=^TestHTTPServerHTTP2HPACKSettingsRace$",
				"-test.count=1",
				"-test.timeout=60s",
				"-test.v",
			)
			cmd.Env = append(os.Environ(),
				"GRAFANA_H2_RACE_CHILD=1",
				"GRAFANA_H2_PROTO="+proto,
			)
			out, err := cmd.CombinedOutput()
			if err != nil {
				t.Fatalf("protocol %s: server did not survive SETTINGS_HEADER_TABLE_SIZE mixed with requests: %v\n%s", proto, err, out)
			}
		})
	}
}

func runHTTP2HeaderTableChild(t *testing.T) {
	t.Helper()
	proto := os.Getenv("GRAFANA_H2_PROTO")

	cfg := setting.NewCfg()
	cfg.MinTLSVersion = "TLS1.2"
	cfg.Domain = "localhost"
	switch proto {
	case "h2":
		cfg.Protocol = setting.HTTP2Scheme
	case "socket_h2":
		cfg.Protocol = setting.SocketHTTP2Scheme
	default:
		t.Fatalf("unsupported protocol %q", proto)
	}

	ln := listenForProtocol(t, proto)
	hs := &HTTPServer{
		log: log.NewNopLogger(),
		Cfg: cfg,
	}
	// Same server construction and TLS switch as HTTPServer.Run. The handler
	// stands in for the mux: any response, including Grafana's, is encoded by
	// http2writeResHeaders on the async frame writer.
	hs.httpSrv = &http.Server{
		Addr:        ln.Addr().String(),
		ReadTimeout: hs.Cfg.ReadTimeout,
		Handler: http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			w.Header().Set("Content-Type", "text/plain")
			w.Header().Set("X-Request-Path", r.URL.Path)
			_, _ = io.WriteString(w, "ok")
		}),
		ErrorLog: stdlog.New(&customErrorLogger{log: hs.log}, "", 0),
	}
	require.NoError(t, hs.configureTLS())

	serveDone := make(chan error, 1)
	go func() {
		err := hs.httpSrv.ServeTLS(ln, "", "")
		serveDone <- err
	}()

	addr := ln.Addr()
	require.Eventually(t, func() bool {
		return dialH2(addr) == nil
	}, 5*time.Second, 20*time.Millisecond)

	deadline := time.Now().Add(2 * time.Second)
	for time.Now().Before(deadline) {
		_ = dialH2(addr)
	}

	select {
	case err := <-serveDone:
		t.Fatalf("ServeTLS returned during the attack: %v", err)
	default:
	}
	var status int
	var getErr error
	require.Eventually(t, func() bool {
		status, getErr = getStatus(addr)
		return getErr == nil && status == http.StatusOK
	}, 3*time.Second, 50*time.Millisecond)
	if getErr != nil {
		t.Fatal(getErr)
	}
}

func listenForProtocol(t *testing.T, proto string) net.Listener {
	t.Helper()
	if proto == "socket_h2" {
		path := filepath.Join(t.TempDir(), "grafana.sock")
		ln, err := net.Listen("unix", path)
		require.NoError(t, err)
		t.Cleanup(func() { _ = ln.Close() })
		return ln
	}
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	require.NoError(t, err)
	t.Cleanup(func() { _ = ln.Close() })
	return ln
}

func dialH2(addr net.Addr) error {
	raw, err := net.Dial(addr.Network(), addr.String())
	if err != nil {
		return err
	}
	defer raw.Close()
	conn := tls.Client(raw, &tls.Config{
		InsecureSkipVerify: true, //nolint:gosec // local server generated by this test
		NextProtos:         []string{"h2"},
		MinVersion:         tls.VersionTLS12,
		ServerName:         "localhost",
	})
	defer conn.Close()
	_ = conn.SetDeadline(time.Now().Add(2 * time.Second))
	if err := conn.Handshake(); err != nil {
		return err
	}
	if conn.ConnectionState().NegotiatedProtocol != "h2" {
		return io.ErrUnexpectedEOF
	}
	go func() { _, _ = io.Copy(io.Discard, conn) }()

	bw := bufio.NewWriter(conn)
	if _, err := bw.WriteString("PRI * HTTP/2.0\r\n\r\nSM\r\n\r\n"); err != nil {
		return err
	}
	if err := writeFrame(bw, 0x4, 0, 0, nil); err != nil {
		return err
	}
	if err := writeFrame(bw, 0x4, 0x1, 0, nil); err != nil {
		return err
	}
	var win [4]byte
	binary.BigEndian.PutUint32(win[:], 1<<20)
	if err := writeFrame(bw, 0x8, 0, 0, win[:]); err != nil {
		return err
	}

	var payload []byte
	for stream := uint32(1); stream < 81; stream += 2 {
		payload = payload[:0]
		payload = appendRequestHeaders(payload, stream)
		payload = appendHeaderTableSize(payload, 0)
		payload = appendHeaderTableSize(payload, 4096)
		if _, err := bw.Write(payload); err != nil {
			return err
		}
	}
	return bw.Flush()
}

func getStatus(addr net.Addr) (int, error) {
	transport := &http.Transport{
		// DialContext disables automatic HTTP/2 unless this is set.
		ForceAttemptHTTP2: true,
		TLSClientConfig: &tls.Config{
			InsecureSkipVerify: true, //nolint:gosec // local server generated by this test
			NextProtos:         []string{"h2"},
			MinVersion:         tls.VersionTLS12,
			ServerName:         "localhost",
		},
		DialContext: func(ctx context.Context, _, _ string) (net.Conn, error) {
			var d net.Dialer
			return d.DialContext(ctx, addr.Network(), addr.String())
		},
	}
	client := &http.Client{Transport: transport, Timeout: 2 * time.Second}
	resp, err := client.Get("https://localhost/")
	if err != nil {
		return 0, err
	}
	defer resp.Body.Close()
	_, _ = io.Copy(io.Discard, resp.Body)
	if resp.Proto != "HTTP/2.0" {
		return 0, io.ErrUnexpectedEOF
	}
	return resp.StatusCode, nil
}

func appendRequestHeaders(dst []byte, stream uint32) []byte {
	// Static table: index 2 is :method GET, index 7 is :scheme https.
	// Index 4 is :path and index 1 is :authority, sent as literal values.
	block := []byte{0x82, 0x87}
	block = appendIndexedName(block, 4, "/")
	block = appendIndexedName(block, 1, "localhost")
	return appendFrame(dst, 0x1, 0x4|0x1, stream, block)
}

func appendIndexedName(dst []byte, nameIdx byte, value string) []byte {
	dst = append(dst, 0x40|nameIdx)
	dst = append(dst, byte(len(value)))
	return append(dst, value...)
}

func appendHeaderTableSize(dst []byte, size uint32) []byte {
	var p [6]byte
	binary.BigEndian.PutUint16(p[0:2], 0x1) // SETTINGS_HEADER_TABLE_SIZE
	binary.BigEndian.PutUint32(p[2:6], size)
	return appendFrame(dst, 0x4, 0, 0, p[:])
}

func appendFrame(dst []byte, typ, flags byte, stream uint32, payload []byte) []byte {
	n := len(payload)
	dst = append(dst,
		byte(n>>16), byte(n>>8), byte(n),
		typ, flags,
		byte(stream>>24), byte(stream>>16), byte(stream>>8), byte(stream),
	)
	return append(dst, payload...)
}

func writeFrame(w io.Writer, typ, flags byte, stream uint32, payload []byte) error {
	_, err := w.Write(appendFrame(nil, typ, flags, stream, payload))
	return err
}
