// TestInstrumentationServerHTTP2HPACKSettingsRace covers the module
// instrumentation listener. When protocol is https it calls ListenAndServeTLS
// without clearing TLSNextProto, so the stdlib HTTP/2 server is on. The same
// SETTINGS_HEADER_TABLE_SIZE race aborts that process on Go 1.26.6.
func TestInstrumentationServerHTTP2HPACKSettingsRace(t *testing.T) {
	if os.Getenv("GRAFANA_H2_RACE_CHILD") == "1" {
		runInstrumentationHeaderTableChild(t)
		return
	}

	cmd := exec.Command(os.Args[0],
		"-test.run=^TestInstrumentationServerHTTP2HPACKSettingsRace$",
		"-test.count=1",
		"-test.timeout=60s",
		"-test.v",
	)
	cmd.Env = append(os.Environ(), "GRAFANA_H2_RACE_CHILD=1")
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("instrumentation server did not survive SETTINGS_HEADER_TABLE_SIZE mixed with requests: %v\n%s", err, out)
	}
}

func runInstrumentationHeaderTableChild(t *testing.T) {
	t.Helper()
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	require.NoError(t, err)
	tcpAddr, ok := ln.Addr().(*net.TCPAddr)
	require.True(t, ok)
	require.NoError(t, ln.Close())

	dir := t.TempDir()
	certPath, keyPath := writeCert(t, dir)

	cfg := setting.NewCfg()
	cfg.Protocol = setting.HTTPSScheme
	cfg.HTTPAddr = "127.0.0.1"
	cfg.HTTPPort = strconv.Itoa(tcpAddr.Port)
	cfg.MinTLSVersion = "TLS1.2"
	cfg.CertFile = certPath
	cfg.KeyFile = keyPath

	ms := &ModuleServer{
		log:          log.NewNopLogger(),
		cfg:          cfg,
		promGatherer: prometheus.NewRegistry(),
	}
	s, err := ms.initInstrumentationServer()
	require.NoError(t, err)
	require.NoError(t, s.start(context.Background()))

	addr := &net.TCPAddr{IP: net.ParseIP("127.0.0.1"), Port: tcpAddr.Port}
	require.Eventually(t, func() bool {
		return dialH2(addr) == nil
	}, 5*time.Second, 20*time.Millisecond)

	deadline := time.Now().Add(2 * time.Second)
	for time.Now().Before(deadline) {
		_ = dialH2(addr)
	}

	var status int
	var getErr error
	require.Eventually(t, func() bool {
		status, getErr = getStatus(addr)
		return getErr == nil && status == http.StatusOK
	}, 3*time.Second, 50*time.Millisecond)
	if getErr != nil {
		t.Fatal(getErr)
	}
}

func writeCert(t *testing.T, dir string) (string, string) {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	require.NoError(t, err)
	tmpl := &x509.Certificate{
		SerialNumber: big.NewInt(1),
		Subject:      pkix.Name{CommonName: "localhost"},
		NotBefore:    time.Now().Add(-time.Hour),
		NotAfter:     time.Now().Add(time.Hour),
		DNSNames:     []string{"localhost"},
		IPAddresses:  []net.IP{net.ParseIP("127.0.0.1")},
		KeyUsage:     x509.KeyUsageDigitalSignature,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
	require.NoError(t, err)
	certPath := filepath.Join(dir, "cert.pem")
	keyPath := filepath.Join(dir, "key.pem")
	certPEM := pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der})
	keyDER, err := x509.MarshalECPrivateKey(key)
	require.NoError(t, err)
	keyPEM := pem.EncodeToMemory(&pem.Block{Type: "EC PRIVATE KEY", Bytes: keyDER})
	require.NoError(t, os.WriteFile(certPath, certPEM, 0o600))
	require.NoError(t, os.WriteFile(keyPath, keyPEM, 0o600))
	return certPath, keyPath
}

func dialH2(addr net.Addr) error {
	raw, err := net.Dial(addr.Network(), addr.String())
	if err != nil {
		return err
	}
	defer raw.Close()
	conn := tls.Client(raw, &tls.Config{
		InsecureSkipVerify: true, //nolint:gosec // local server generated by this test
		NextProtos:         []string{"h2"},
		MinVersion:         tls.VersionTLS12,
		ServerName:         "localhost",
	})
	defer conn.Close()
	_ = conn.SetDeadline(time.Now().Add(2 * time.Second))
	if err := conn.Handshake(); err != nil {
		return err
	}
	if conn.ConnectionState().NegotiatedProtocol != "h2" {
		return io.ErrUnexpectedEOF
	}
	go func() { _, _ = io.Copy(io.Discard, conn) }()

	bw := bufio.NewWriter(conn)
	if _, err := bw.WriteString("PRI * HTTP/2.0\r\n\r\nSM\r\n\r\n"); err != nil {
		return err
	}
	if err := writeFrame(bw, 0x4, 0, 0, nil); err != nil {
		return err
	}
	if err := writeFrame(bw, 0x4, 0x1, 0, nil); err != nil {
		return err
	}
	var win [4]byte
	binary.BigEndian.PutUint32(win[:], 1<<20)
	if err := writeFrame(bw, 0x8, 0, 0, win[:]); err != nil {
		return err
	}

	var payload []byte
	for stream := uint32(1); stream < 81; stream += 2 {
		payload = payload[:0]
		payload = appendRequestHeaders(payload, stream)
		payload = appendHeaderTableSize(payload, 0)
		payload = appendHeaderTableSize(payload, 4096)
		if _, err := bw.Write(payload); err != nil {
			return err
		}
	}
	return bw.Flush()
}

func getStatus(addr net.Addr) (int, error) {
	transport := &http.Transport{
		// DialContext disables automatic HTTP/2 unless this is set.
		ForceAttemptHTTP2: true,
		TLSClientConfig: &tls.Config{
			InsecureSkipVerify: true, //nolint:gosec // local server generated by this test
			NextProtos:         []string{"h2"},
			MinVersion:         tls.VersionTLS12,
			ServerName:         "localhost",
		},
		DialContext: func(ctx context.Context, _, _ string) (net.Conn, error) {
			var d net.Dialer
			return d.DialContext(ctx, addr.Network(), addr.String())
		},
	}
	client := &http.Client{Transport: transport, Timeout: 2 * time.Second}
	resp, err := client.Get("https://localhost/metrics")
	if err != nil {
		return 0, err
	}
	defer resp.Body.Close()
	_, _ = io.Copy(io.Discard, resp.Body)
	if resp.Proto != "HTTP/2.0" {
		return 0, io.ErrUnexpectedEOF
	}
	return resp.StatusCode, nil
}

func appendRequestHeaders(dst []byte, stream uint32) []byte {
	block := []byte{0x82, 0x87}
	block = appendIndexedName(block, 4, "/metrics")
	block = appendIndexedName(block, 1, "localhost")
	return appendFrame(dst, 0x1, 0x4|0x1, stream, block)
}

func appendIndexedName(dst []byte, nameIdx byte, value string) []byte {
	dst = append(dst, 0x40|nameIdx)
	dst = append(dst, byte(len(value)))
	return append(dst, value...)
}

func appendHeaderTableSize(dst []byte, size uint32) []byte {
	var p [6]byte
	binary.BigEndian.PutUint16(p[0:2], 0x1)
	binary.BigEndian.PutUint32(p[2:6], size)
	return appendFrame(dst, 0x4, 0, 0, p[:])
}

func appendFrame(dst []byte, typ, flags byte, stream uint32, payload []byte) []byte {
	n := len(payload)
	dst = append(dst,
		byte(n>>16), byte(n>>8), byte(n),
		typ, flags,
		byte(stream>>24), byte(stream>>16), byte(stream>>8), byte(stream),
	)
	return append(dst, payload...)
}

func writeFrame(w io.Writer, typ, flags byte, stream uint32, payload []byte) error {
	_, err := w.Write(appendFrame(nil, typ, flags, stream, payload))
	return err
}
